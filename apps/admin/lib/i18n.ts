export type Key = keyof typeof EN;

/**
 * Translate. Falls back to English, then to the key itself.
 *
 * The final fallback returns the key rather than an empty string on purpose: an
 * empty label is invisible in review and ships, whereas `mem.title` on a heading
 * is caught by whoever looks at the page once.
 */
export function t(lang: Lang, key: Key | string): string {
  if (lang === 'ar') return AR[key] ?? EN[key] ?? String(key);
  return EN[key] ?? String(key);
}

/**
 * Translate with {placeholders} filled in.
 *
 * Sentences that wrap numbers had been assembled in JSX out of a dozen string
 * fragments and `{' '}` joins. That cannot be translated: Arabic puts the parts
 * in a different order, and a fragment list has no order to change. One string
 * with named holes can be reordered freely by whoever writes the translation.
 */
export function tf(lang: Lang, key: Key | string, vars: Record<string, string | number>): string {
  return Object.entries(vars).reduce(
    (out, [k, v]) => out.replaceAll(`{${k}}`, String(v)),
    t(lang, key),
  );
}

/**
 * Dates, in the interface language.
 *
 * ⚠ TWO TRAPS, BOTH OF WHICH PUT A WRONG DATE IN FRONT OF A CASHIER.
 *
 * 1. `ar-SA` DEFAULTS TO THE ISLAMIC CALENDAR. Left alone it prints a Hijri
 *    date against a Gregorian receipt and a Gregorian POS. `ca-gregory` is not
 *    optional here.
 * 2. Arabic locales default to Arabic-Indic digits. Every other number in this
 *    portal is Western so it can be read aloud and matched to a printed
 *    receipt; a date must not be the exception. `nu-latn` forces that.
 *
 * The result is an Arabic month name with Western numerals on a Gregorian
 * calendar, which is what a Saudi till actually uses.
 */
export function fmtDate(
  lang: Lang,
  value: string | Date,
  opts: Intl.DateTimeFormatOptions,
): string {
  const locale = lang === 'ar' ? 'ar-SA-u-ca-gregory-nu-latn' : 'en-GB';
  // ⚠ 24-hour, always. Arabic locales default to a 12-hour clock with a ص/م
  // marker; English here is already 24-hour, so leaving it would put two
  // different clocks on the same screen depending on the language, and neither
  // would match a receipt printed in 24-hour. `hourCycle` also avoids a
  // one-character marker that bidi has to place, which is one less thing to go
  // wrong beside a timestamp.
  return new Date(value).toLocaleString(locale, {
    ...opts,
    hourCycle: 'h23',
    // ⚠ PINNED TO RIYADH, NOT THE SERVER'S CLOCK. The container runs in UTC with
    // no TZ set, so every timestamp on every screen was three hours behind the
    // shop. That is not cosmetic here: trade runs 16:00-04:00, so a ticket rung
    // up at 01:00 displayed as 22:00 and read as the previous evening — against
    // a `service_date` the database computes correctly in Asia/Riyadh.
    //
    // Pinned rather than fixed by setting TZ on the container, because that
    // makes correctness depend on deployment configuration nobody re-checks.
    // One branch, one timezone, stated where the formatting happens.
    timeZone: 'Asia/Riyadh',
  });
}

/** Every key with no Arabic yet. Used by the test that guards coverage. */
export function untranslated(): string[] {
  return Object.keys(EN).filter((k) => !(k in AR));
}
